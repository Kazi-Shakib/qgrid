#!/usr/bin/env python3
"""Generate the ProVerif models of the key-delivery architectures (replaces the Tamarin models).

One file per (architecture, compromise scenario). Phases encode time: phase 0 is the protocol run,
including share delivery; phase 1 is "after delivery". Outstation B is always compromised (its
gateway requests and responses use the public channel). Gateway compromise:
  pre  = the gateway leaks every share it holds during phase 0 (compromised before delivery);
  post = the gateway leaks, in phase 1, the shares it still holds (compromised after delivery).
Erasure: a held share is either released to its recipient (and deleted) or still held at phase 1.
To keep ProVerif's over-approximation from merging the two outcomes, the outcome is an attacker
input taken before the share is generated, so the two cases yield different names."""
import itertools, os

ARCH = {   # npath, bind, erase, meta ('auth' from KME, 'net' announced over the network), sae
    'gw1_unbound': dict(npath=1, bind=0, erase=1, meta='auth', sae=0),
    'gw1_bound':   dict(npath=1, bind=1, erase=1, meta='auth', sae=0),
    'p2_nobind':   dict(npath=2, bind=0, erase=1, meta='auth', sae=0),
    'p2_retain':   dict(npath=2, bind=1, erase=0, meta='auth', sae=0),
    'p2_netrcpt':  dict(npath=2, bind=1, erase=1, meta='net',  sae=0),
    'rb2k':        dict(npath=2, bind=1, erase=1, meta='auth', sae=0),
    'sae':         dict(npath=1, bind=1, erase=1, meta='auth', sae=1),
}
SCEN = {   # (G1 pre, G1 post, G2 pre, G2 post, forged announcements)
    'S0': (0, 0, 0, 0, 0),
    'S1': (1, 1, 0, 0, 0),   # G1 compromised throughout
    'S2': (1, 0, 1, 0, 0),   # G1, then G2, both before delivery
    'S3': (1, 1, 0, 1, 0),   # G1 throughout, G2 only after delivery
    'S4': (0, 0, 0, 0, 1),   # forged recipient announcements
}

HEAD = r"""(* generated by gen.py: %(name)s *)
free c: channel.
free reqA1, reqA2, respA1, respA2, ann1, ann2: channel [private].
type id.
free A, B, M: id.
const hello, v13, v15, v6, tel, cmd, reqB, tMASTER, tOUTST, tSK, tTELM, tCTRL, none: bitstring.

fun mac(bitstring, bitstring): bitstring.
fun comb(bitstring, bitstring): bitstring.          (* K = q1 XOR q2: needs both shares *)
fun senc(bitstring, bitstring): bitstring.
reduc forall m: bitstring, k: bitstring; sdec(senc(m, k), k) = m.

event M_Intend(id, id, bitstring, bitstring).
event M_Accept(id, id, bitstring, bitstring).
event M_SK(id, id, bitstring, bitstring).
event O_Accept(id, id, bitstring, bitstring).
event O_SK(id, id, bitstring, bitstring).
event O_SendTel(id, id, bitstring, bitstring).
event M_AcceptTel(id, id, bitstring, bitstring).
event M_SendCmd(id, id, bitstring, bitstring).
event O_AcceptCmd(id, id, bitstring, bitstring).
event BrokenK(bitstring).
event BrokenSK(bitstring).
"""

def gate(g, kid, q, T, a, s, leak_relay):
    """Gateway g (or, for SAE outstations, KME_B) holding share q for target T."""
    pre, post = (s[0], s[1]) if g == 1 else (s[2], s[3])
    if a['sae']: pre = post = 0                     # no gateway: KME_B releases to the named SAE
    cond_A = "" if not a['bind'] else f"if {T} = A then "
    cond_B = "" if not a['bind'] else f"if {T} = B then "
    rel = (f"((in(reqA{g}, ={kid}); {cond_A}out(respA{g}, ({kid}, {q})))"
           f" | (in(c, (=reqB, ={kid})); {cond_B}out(c, {q})))")
    parts = []
    if pre: parts.append(f"out(c, {q})")
    if leak_relay: parts.append(f"out(c, {q})")
    if post and a['erase']:
        parts.append(f"(if held{g} then (phase 1; out(c, {q})) else {rel})")
    elif post:
        parts.append(rel); parts.append(f"(phase 1; out(c, {q}))")
    else:
        parts.append(rel)
    return " | ".join(parts)

def model(name, a, s, relay):
    fa = s[4]
    np2 = a['npath'] == 2
    sc_post_erase = a['erase'] and not a['sae']
    holds = []
    for g in (1, 2) if np2 else (1,):
        post = s[1] if g == 1 else s[3]
        if post and sc_post_erase: holds.append(g)
    choose = "".join(f"in(c, held{g}: bool); " for g in holds)
    news = "new kid1: bitstring; new q1: bitstring; " + ("new kid2: bitstring; new q2: bitstring; " if np2 else "")
    K = "comb(q1, q2)" if np2 else "q1"
    kid2 = "kid2" if np2 else "none"
    def targets(o):
        if a['meta'] == 'net':        # gateways learn the recipient from an announcement
            src = "c" if fa else None
            res = ""
            for g in (1, 2) if np2 else (1,):
                if fa: res += f"in(c, T{g}: id); "
                else: res += f"let T{g} = {o} in "
            return res
        return "".join(f"let T{g} = {o} in " for g in ((1, 2) if np2 else (1,)))
    def gates(o):
        rl = {1: bool(relay and (relay[0] & 1)), 2: bool(relay and (relay[0] & (1 if relay[1] == 'shared' else 2)))}
        out = [gate(1, "kid1", "q1", "T1", a, s, rl[1])]
        if np2: out.append(gate(2, "kid2", "q2", "T2", a, s, rl[2]))
        return " | ".join(f"({x})" for x in out)
    master_A = f"""
let MasterA =
  in(c, (=hello, =A, nO: bitstring));
  {choose}{news}
  let K = {K} in
  let C = (M, A, kid1, {kid2}, nO) in
  event M_Intend(M, A, K, C);
  {targets('A')}
  ( {gates('A')}
  | ( out(c, (v13, C, mac((tMASTER, C), K)));
      in(c, (=v15, tO: bitstring));
      if tO = mac((tOUTST, C), K) then
      event M_Accept(M, A, K, C);
      new sk: bitstring;
      event M_SK(M, A, sk, C);
      out(c, (v6, senc((tSK, sk, C), K)));
      ( (phase 1; in(c, gK: bitstring); if gK = K then event BrokenK(K))
      | (phase 1; in(c, gS: bitstring); if gS = sk then event BrokenSK(sk))
      | !(in(c, (=tel, =A, d: bitstring, t: bitstring)); if t = mac((tTELM, A, M, d), sk) then event M_AcceptTel(M, A, d, sk))
      | !(new x: bitstring; event M_SendCmd(M, A, x, sk); out(c, (cmd, A, x, mac((tCTRL, M, A, x), sk)))) ) ) ).
"""
    master_B = f"""
let MasterB =       (* sessions with the compromised outstation B *)
  in(c, (=hello, =B, nO: bitstring));
  {choose}{news}
  {targets('B')}
  ( {gates('B')} | out(c, (kid1, {kid2}))).
"""
    fetch2 = "out(reqA2, kid2); in(respA2, (=kid2, q2: bitstring)); " if np2 else ""
    outA = f"""
let OutA =
  new nO: bitstring;
  out(c, (hello, A, nO));
  in(c, (=v13, (m: id, =A, kid1: bitstring, kid2: bitstring, =nO), t: bitstring));
  out(reqA1, kid1); in(respA1, (=kid1, q1: bitstring));
  {fetch2}let K = {K} in
  let C = (m, A, kid1, kid2, nO) in
  if t = mac((tMASTER, C), K) then
  event O_Accept(A, m, K, C);
  out(c, (v15, mac((tOUTST, C), K)));
  in(c, (=v6, e: bitstring));
  let (=tSK, sk: bitstring, =C) = sdec(e, K) in
  event O_SK(A, m, sk, C);
  ( !(new d: bitstring; event O_SendTel(A, m, d, sk); out(c, (tel, A, d, mac((tTELM, A, m, d), sk))))
  | !(in(c, (=cmd, =A, x: bitstring, t2: bitstring)); if t2 = mac((tCTRL, m, A, x), sk) then event O_AcceptCmd(A, m, x, sk)) ).
"""
    q = """
(* Q1 update-key secrecy, Q2 session-key secrecy (phase 1 covers knowledge gained at any time) *)
query k: bitstring; event(BrokenK(k)).
query k: bitstring; event(BrokenSK(k)).
(* Q3 injective agreement on the context C (outstation side) *)
query o: id, m: id, k: bitstring, cc: bitstring; inj-event(O_Accept(o, m, k, cc)) ==> inj-event(M_Intend(m, o, k, cc)).
"""
    full = name.startswith('rb2k_S') and not name.endswith('S2') and not relay
    if full:
        q += """
(* Q4 session-key agreement *)
query o: id, m: id, s: bitstring, cc: bitstring; event(O_SK(o, m, s, cc)) ==> event(M_SK(m, o, s, cc)).
(* Q5 telemetry origin, Q6 command origin, bound to the session key and accepted context *)
query m: id, o: id, d: bitstring, s: bitstring, cc: bitstring;
  event(M_AcceptTel(m, o, d, s)) && event(M_SK(m, o, s, cc)) ==> event(O_SendTel(o, m, d, s)) && event(O_SK(o, m, s, cc)).
query m: id, o: id, x: bitstring, s: bitstring, cc: bitstring;
  event(O_AcceptCmd(o, m, x, s)) && event(O_SK(o, m, s, cc)) ==> event(M_SendCmd(m, o, x, s)) && event(M_SK(m, o, s, cc)).
(* Q7-Q8 executability: these must come back "false" (the events are reachable) *)
query m: id, o: id, d: bitstring, s: bitstring; event(M_AcceptTel(m, o, d, s)).
query m: id, o: id, x: bitstring, s: bitstring; event(O_AcceptCmd(o, m, x, s)).
"""
    proc = "\nprocess !MasterA | !MasterB | !OutA\n"
    return HEAD % {'name': name} + q + master_A + master_B + outA + proc

os.makedirs('models', exist_ok=True)
files = []
for an, a in ARCH.items():
    for sn, s in SCEN.items():
        n = f"{an}_{sn}"; files.append(n)
        open(f"models/{n}.pv", 'w').write(model(n, a, s, None))
# trusted-node relays: (bitmask of compromised relays, routing of share 2)
for an, base, route in (('relay_gw1_bound', 'gw1_bound', 'shared'), ('relay_sae', 'sae', 'shared'),
                        ('relay_rb2k_sharedT1', 'rb2k', 'shared'), ('relay_rb2k_disjoint', 'rb2k', 'disjoint')):
    for tn in (0, 1, 3):
        n = f"{an}_tn{tn}"; files.append(n)
        open(f"models/{n}.pv", 'w').write(model(n, ARCH[base], SCEN['S0'], (tn, route)))
open('models/LIST', 'w').write("\n".join(files) + "\n")
print(len(files), "models")
